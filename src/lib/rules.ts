export type SectionId = keyof typeof SECTIONS;

export function isSectionId(value: unknown): value is SectionId {
  return typeof value === "string" && Object.hasOwn(SECTIONS, value);
}

interface RulesFile {
  id: string;
  version: string;
  body: string;
  /** Every front-matter field, as written (id and version included). */
  fields: Record<string, string>;
}

function parseRulesFile(raw: string, fileName: string): RulesFile {
  // A Windows checkout or editor may turn line endings into CRLF; the format is the same.
  const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw.replace(/\r\n/g, "\n"));
  if (!match) throw new Error(`Rules file ${fileName} has no front matter.`);
  const fields = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const [key, ...rest] = line.split(":");
      return [key.trim(), rest.join(":").trim()];
    }),
  );
  if (!fields.id || !fields.version) throw new Error(`Rules file ${fileName} needs id and version.`);
  return { id: fields.id, version: fields.version, body: match[2].trim(), fields };
}

const cache = new Map<string, Promise<RulesFile>>();

function loadRulesFile(rulesDir: string, relativePath: string): Promise<RulesFile> {
  const fullPath = path.join(rulesDir, relativePath);
  let pending = cache.get(fullPath);
  if (!pending) {
    pending = readFile(fullPath, "utf8").then((raw) => parseRulesFile(raw, relativePath));
    // In development the files are re-read on every request so edits show up at once.
    if (process.env.NODE_ENV === "production") cache.set(fullPath, pending);
  }
  return pending;
}

export async function buildPrompt(
  sectionId: SectionId,
  sources: SourceDocument[],
  rulesDir: string = DEFAULT_RULES_DIR,
): Promise<{ prompt: PromptParts; rulesVersions: Record<string, string> }> {
  const section = SECTIONS[sectionId];
  const [systemFiles, sectionFile] = await Promise.all([
    Promise.all(SYSTEM_FILES.map((file) => loadRulesFile(rulesDir, file))),
    loadRulesFile(rulesDir, section.file),
  ]);

  const rulesVersions = Object.fromEntries([...systemFiles, sectionFile].map((f) => [f.id, f.version]));
  const system = systemFiles.map((f) => f.body).join("\n\n---\n\n");
  const task = [
    sectionFile.body,
    "---",
    `Write the "${section.title}" section (section ${section.templateNumber} of the ABA Matrix template) for the client described in the sources. Use only what the sources say. Return only the text of the section, ready to paste.`,
  ].join("\n\n");

  return { prompt: { system, sources, task }, rulesVersions };
}

function parseRange(value: string | undefined): { min: number; max: number } | null {
  const match = /^(\d+)\s*-\s*(\d+)$/.exec(value ?? "");
  if (!match) return null;
  const min = Number(match[1]);
  const max = Number(match[2]);
  return min <= max ? { min, max } : null;
}

/** The shape a section's rules file declares in its front matter ("paragraphs: 6-9", "words: 900-1500"). */
export async function loadSectionShape(sectionId: SectionId, rulesDir: string = DEFAULT_RULES_DIR): Promise<SectionShape> {
  const file = await loadRulesFile(rulesDir, SECTIONS[sectionId].file);
  return { paragraphs: parseRange(file.fields.paragraphs), words: parseRange(file.fields.words) };
}

/** Another section of the report that the BCBA wrote or approved: final, sent as context. */
export interface ContextSection {
  title: string;
  text: string;
}

/**
 * What one request of the section workspace asks:
 * - "draft": write the section from the sources;
 * - "change": rewrite the whole text as she asks, in her own words;
 * - "paragraph": rewrite one paragraph only (the answer is that paragraph alone);
 * - "improve": improve a text she wrote herself.
 */
export type SectionRequest =
  | { kind: "draft" }
  | { kind: "change"; currentText: string; request: string }
  | { kind: "paragraph"; currentText: string; paragraphIndex: number; request: string }
  | { kind: "improve"; currentText: string }
  /**
   * Checks a version against her sections, and against her own text of this section when
   * there is one (ownText); the answer is CONSISTENCY_NONE or one "- " line per contradiction.
   */
  | { kind: "consistency"; currentText: string; ownText: string | null; herRequest: string | null };

/** The answer of a consistency check that found nothing. */
export const CONSISTENCY_NONE = "NO CONTRADICTIONS";
/** What a check's result keeps: as the case's data file reads it back (src/main/case-file.ts). */
export const MAX_CONSISTENCY_ITEMS = 20;
export const MAX_CONSISTENCY_ITEM_LENGTH = 2000;

/** A consistency check's answer as a list of contradictions (empty: none). Null when the answer is not in the expected shape. */
export function parseConsistencyAnswer(answer: string): string[] | null {
  const text = answer.trim();
  if (text.replace(/[.\s]+$/u, "").toUpperCase() === CONSISTENCY_NONE) return [];
  const items = text
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line.startsWith("- "))
    .map((line) => line.slice(2).trim())
    .filter((line) => line !== "");
  // Clamped to what the data file accepts: a longer line is cut, never allowed to make the case unreadable.
  return items.length > 0 ? items.slice(0, MAX_CONSISTENCY_ITEMS).map((item) => (item.length > MAX_CONSISTENCY_ITEM_LENGTH ? `${item.slice(0, MAX_CONSISTENCY_ITEM_LENGTH - 1)}…` : item)) : null;
}

export interface SectionPromptInput {
  section: SectionId;
  request: SectionRequest;
  sources: SourceDocument[];
  /** Her other sections that are hers or approved, in the report's order. Never this section. */
  herSections: ContextSection[];
  /** Her standing instructions for this section, for all her cases. */
  instructions: string | null;
  /** Her notes for this session. */
  notes: string | null;
}

/** The tags the section prompt uses: text she typed can never open or close one of them. */
const PROMPT_TAGS = ["her-sections", "section", "standing-instructions", "session-notes", "current-text", "marked-paragraph", "her-request", "her-own-text", "source", "sources"];
const TAG_PATTERN = new RegExp(`<(/?)(${PROMPT_TAGS.join("|")})\\b`, "giu");

/** Text typed or pasted by her, made unable to break out of the tag it is put in. */
export function quoteForPrompt(text: string): string {
  return text.replace(TAG_PATTERN, (_whole, slash: string, name: string) => `‹${slash}${name}`).trim();
}

function currentTextBlock(text: string, markedIndex: number | null): string {
  const paragraphs = splitParagraphs(text).map((paragraph, index) => {
    const quoted = quoteForPrompt(paragraph);
    return index === markedIndex ? `<marked-paragraph>\n${quoted}\n</marked-paragraph>` : quoted;
  });
  return `<current-text>\n${paragraphs.join("\n\n")}\n</current-text>`;
}

/**
 * The prompt of one request of the section workspace. The cached prefix (system: the
 * assessment rules, the payer facts, the instruments and how requests work; then the
 * sources) is the same for every request of one case; everything that changes from one
 * request to the next goes in the task, after it.
 */
export async function buildSectionPrompt(
  input: SectionPromptInput,
  rulesDir: string = DEFAULT_RULES_DIR,
): Promise<{ prompt: PromptParts; rulesVersions: Record<string, string> }> {
  const section = SECTIONS[input.section];
  const [systemFiles, sectionFile] = await Promise.all([
    Promise.all(SECTION_REQUEST_SYSTEM_FILES.map((file) => loadRulesFile(rulesDir, file))),
    loadRulesFile(rulesDir, section.file),
  ]);
  const rulesVersions = Object.fromEntries([...systemFiles, sectionFile].map((f) => [f.id, f.version]));
  const system = systemFiles.map((f) => f.body).join("\n\n---\n\n");

  const parts: string[] = [sectionFile.body, "---"];
  if (input.herSections.length > 0) {
    const blocks = input.herSections.map((other) => `<section title="${other.title}">\n${quoteForPrompt(other.text)}\n</section>`);
    parts.push(`<her-sections>\n${blocks.join("\n\n")}\n</her-sections>`);
  }
  const instructions = input.instructions?.trim();
  if (instructions) parts.push(`<standing-instructions>\n${quoteForPrompt(instructions)}\n</standing-instructions>`);
  const notes = input.notes?.trim();
  if (notes) parts.push(`<session-notes>\n${quoteForPrompt(notes)}\n</session-notes>`);

  const what = `the "${section.title}" section (section ${section.templateNumber} of the ABA Matrix template)`;
  const request = input.request;
  switch (request.kind) {
    case "draft":
      parts.push(`Draft request. Write ${what} for the client described in the sources. Use only what the sources, her sections and her notes say. Return only the text of the section, ready to paste.`);
      break;
    case "change":
      parts.push(currentTextBlock(request.currentText, null));
      parts.push(`<her-request>\n${quoteForPrompt(request.request)}\n</her-request>`);
      parts.push(`Change request for ${what}. Make the change she asks for and return the whole section, ready to paste.`);
      break;
    case "paragraph":
      parts.push(currentTextBlock(request.currentText, request.paragraphIndex));
      parts.push(`<her-request>\n${quoteForPrompt(request.request)}\n</her-request>`);
      parts.push(`Paragraph change request for ${what}. Return only the new text of the marked paragraph: one paragraph, nothing else.`);
      break;
    case "improve":
      parts.push(currentTextBlock(request.currentText, null));
      parts.push(
        [
          `Improve request. The text above is ${what} as she wrote it.`,
          "Keep every fact of hers exactly as she wrote it: times, dates, ages, numbers, scores, names, places, frequencies and durations. Never correct, round or replace one, even where a source says otherwise; keep hers and add [CHECK: what the source says] right after it.",
          "Return the improved section, ready to paste.",
        ].join("\n"),
      );
      break;
    case "consistency": {
      parts.push(currentTextBlock(request.currentText, null));
      const ownText = request.ownText?.trim();
      if (ownText) parts.push(`<her-own-text>\n${quoteForPrompt(ownText)}\n</her-own-text>`);
      // The change she asked for, when the version answers one: what she asked to change is not a contradiction (review round 1, F1).
      const herRequest = ownText ? request.herRequest?.trim() : undefined;
      if (herRequest) parts.push(`<her-request>\n${quoteForPrompt(herRequest)}\n</her-request>`);
      const against = ownText ? "her sections and with her own text of this section in <her-own-text>" : "her sections only";
      parts.push(
        [
          `Consistency check. The text above is a new version of ${what}. Compare it with ${against}: does it contradict any of them in names, numbers, scores, dates, times, behaviors, diagnoses, settings, people or services?`,
          ...(ownText
            ? [
                "Her own text is hers. A fact of it that the new version replaces with another value (a time, a date, a number, a name) is a contradiction, with or without a [CHECK: ...] beside it. Her fact kept as she wrote it, with a [CHECK: ...] beside it quoting what a source says, is not a contradiction, and neither is a fact of hers that the new version leaves out.",
              ]
            : []),
          ...(herRequest
            ? [
                "The new version answers what she asked for in <her-request>: a difference from her own text that she asked for there is not a contradiction.",
                // Review round 2, R1: a fact she set by a request and a later version quietly put back is caught too.
                "Where she asked in <her-request> for a fact to change, the value she asked for is now her fact: a new version that keeps her old value or gives a third one is a contradiction (unless a later request of hers changed it again).",
              ]
            : []),
          "Do not report missing information, style, length, or differences of emphasis; only statements that cannot both be true.",
          `If there is no contradiction, answer exactly: ${CONSISTENCY_NONE}`,
          `Otherwise answer with one line per contradiction, each starting with "- ", naming her section${ownText ? ' (or "Her own text" for her text of this section)' : ""} and saying briefly what differs. Nothing else.`,
        ].join("\n"),
      );
      break;
    }
  }
  return { prompt: { system, sources: input.sources, task: parts.join("\n\n") }, rulesVersions };
}
